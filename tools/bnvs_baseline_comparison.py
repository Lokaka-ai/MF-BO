#!/usr/bin/env python3
"""Strictly prequential offline comparison of BNVS selector baselines.

Factual value metrics use all historical runs.  Policy replay uses the Legacy
runs generated by Progressive MCGS; outcomes are known only when a replayed
policy selects the same action as that logged policy.
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import replace
import hashlib
import json
import math
from pathlib import Path
import sys

import numpy as np
from scipy.stats import spearmanr


REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from engine.parent_selectors.base import NORMAL_OPERATORS  # noqa: E402
from engine.parent_selectors.surrogate import (  # noqa: E402
    BayesianNodeValueSurrogate,
)
from engine.parent_selectors.transition_store import TransitionRecord  # noqa: E402
from reward_only_acquisition_replay import candidate_groups  # noqa: E402
from reward_only_offline_eval import (  # noqa: E402
    json_safe,
    normalized_ranks,
    read_jsonl,
    snapshot_features_by_decision,
)


BASELINES = (
    "progressive_mcgs",
    "bnvs_mean_greedy",
    "bnvs_ts",
    "bnvs_ts_local",
)


def stable_seed(*parts: str) -> int:
    digest = hashlib.sha256("|".join(parts).encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "big", signed=False)


def safe_spearman(actual: np.ndarray, predicted: np.ndarray) -> float | None:
    if len(actual) < 2 or np.all(actual == actual[0]) or np.all(predicted == predicted[0]):
        return None
    value = float(spearmanr(actual, predicted).statistic)
    return value if math.isfinite(value) else None


def h1_target(record: TransitionRecord, *, scale: float) -> float:
    if not record.valid or record.child_utility is None:
        return -1.0
    pre_action_best = record.selection_features.get("global_best_utility")
    if pre_action_best is None:
        pre_action_best = record.parent_utility
    if pre_action_best is None:
        return -1.0
    raw = (float(record.child_utility) - float(pre_action_best)) / max(scale, 1e-12)
    return float(min(max(raw, -1.0), 1.0))


def local_mean_as_h1(
    record: TransitionRecord,
    *,
    local_mean: float,
    scale: float,
) -> float:
    parent = float(record.parent_utility or 0.0)
    pre_action_best = float(
        record.selection_features.get("global_best_utility", parent) or 0.0
    )
    return float(local_mean + (parent - pre_action_best) / max(scale, 1e-12))


def selected_index(options, selected_key: tuple[str, str]) -> int:
    return next(
        index for index, option in enumerate(options)
        if (option.parent_node_id, option.operator) == selected_key
    )


def history_bucket(count: int) -> str:
    if count == 0:
        return "0"
    if count <= 2:
        return "1-2"
    if count <= 5:
        return "3-5"
    if count <= 9:
        return "6-9"
    return "10+"


def policy_row(
    *,
    method: str,
    options,
    chosen_index: int,
    historical_index: int,
    actual_target: float,
    invalid: bool,
    history_normal: int,
    stability_modal_share: float | None,
) -> dict:
    utilities = [option.parent_utility for option in options]
    ranks = normalized_ranks(utilities)
    factual = chosen_index == historical_index
    return {
        "baseline": method,
        "history_normal": history_normal,
        "history_bucket": history_bucket(history_normal),
        "candidate_count": len(options),
        "historical_mcgs_agreement": factual,
        "selected_parent_rank": ranks[chosen_index],
        "selected_max_parent": math.isclose(
            utilities[chosen_index],
            max(utilities),
            rel_tol=1e-12,
            abs_tol=1e-12,
        ),
        "stability_modal_share": stability_modal_share,
        "factual": factual,
        "factual_target": actual_target if factual else None,
        "factual_new_incumbent": actual_target > 0.0 if factual else None,
        "factual_invalid": invalid if factual else None,
    }


def evaluate_run(
    transition_path: Path,
    *,
    runs_root: Path,
    stability_seeds: int,
) -> tuple[list[dict], list[dict], dict]:
    relative = transition_path.relative_to(runs_root)
    logged_method, task, run_name = relative.parts[:3]
    snapshot_path = transition_path.parent / "selection_snapshots.jsonl"
    feature_lookup = snapshot_features_by_decision(snapshot_path)
    groups = candidate_groups(snapshot_path)
    records = [
        TransitionRecord.from_dict(row) for row in read_jsonl(transition_path)
    ]

    history: list[TransitionRecord] = []
    normal_count = 0
    factual_rows: list[dict] = []
    policy_rows: list[dict] = []
    errors = 0

    for record in records:
        exact_features = feature_lookup.get(record.decision_id)
        enriched = (
            replace(record, selection_features=exact_features)
            if exact_features is not None else record
        )
        if enriched.operator not in NORMAL_OPERATORS:
            history.append(enriched)
            continue

        try:
            h1_model = BayesianNodeValueSurrogate(target_type="incumbent_h1")
            local_model = BayesianNodeValueSurrogate(target_type="local_gain")
            h1_model.fit(history)
            local_model.fit(history)
            option = next((
                candidate
                for candidate in (groups.get(enriched.decision_id) or ([], None))[0]
                if candidate.parent_node_id == enriched.parent_node_id
                and candidate.operator == enriched.operator
            ), None)
            if option is None:
                from reward_only_offline_eval import option_from_record
                option = option_from_record(enriched)
            h1_mean, _ = h1_model.predict_values([option])
            local_mean, _ = local_model.predict_values([option])
            actual = h1_target(enriched, scale=h1_model.utility_scale)
            local_h1 = local_mean_as_h1(
                enriched,
                local_mean=float(local_mean[0]),
                scale=local_model.utility_scale,
            )
            factual_rows.append({
                "logged_method": logged_method,
                "task": task,
                "run": run_name,
                "transition_id": enriched.transition_id,
                "history_normal": normal_count,
                "history_bucket": history_bucket(normal_count),
                "actual_h1": actual,
                "invalid": not enriched.valid or enriched.child_utility is None,
                "bnvs_h1_mean": float(h1_mean[0]),
                "bnvs_local_as_h1_mean": local_h1,
            })

            group = groups.get(enriched.decision_id)
            if logged_method == "Legacy" and group is not None and len(group[0]) >= 2:
                options, historical_key = group
                historical_index = selected_index(options, historical_key)
                h1_means, _ = h1_model.predict_values(options)
                local_means, _ = local_model.predict_values(options)
                h1_index = int(np.argmax(h1_means))

                h1_choices = []
                local_choices = []
                for seed_index in range(stability_seeds):
                    seed = stable_seed(
                        task, run_name, enriched.decision_id, str(seed_index)
                    )
                    h1_choices.append(int(np.argmax(
                        h1_model.sample_values(options, seed=seed)
                    )))
                    local_choices.append(int(np.argmax(
                        local_model.sample_values(options, seed=seed)
                    )))
                h1_ts_index = h1_choices[0]
                local_ts_index = local_choices[0]
                h1_modal = max(Counter(h1_choices).values()) / len(h1_choices)
                local_modal = max(Counter(local_choices).values()) / len(local_choices)

                policy_rows.extend([
                    policy_row(
                        method="progressive_mcgs",
                        options=options,
                        chosen_index=historical_index,
                        historical_index=historical_index,
                        actual_target=actual,
                        invalid=not enriched.valid or enriched.child_utility is None,
                        history_normal=normal_count,
                        stability_modal_share=None,
                    ),
                    policy_row(
                        method="bnvs_mean_greedy",
                        options=options,
                        chosen_index=h1_index,
                        historical_index=historical_index,
                        actual_target=actual,
                        invalid=not enriched.valid or enriched.child_utility is None,
                        history_normal=normal_count,
                        stability_modal_share=1.0,
                    ),
                    policy_row(
                        method="bnvs_ts",
                        options=options,
                        chosen_index=h1_ts_index,
                        historical_index=historical_index,
                        actual_target=actual,
                        invalid=not enriched.valid or enriched.child_utility is None,
                        history_normal=normal_count,
                        stability_modal_share=h1_modal,
                    ),
                    policy_row(
                        method="bnvs_ts_local",
                        options=options,
                        chosen_index=local_ts_index,
                        historical_index=historical_index,
                        actual_target=actual,
                        invalid=not enriched.valid or enriched.child_utility is None,
                        history_normal=normal_count,
                        stability_modal_share=local_modal,
                    ),
                ])
        except Exception:
            errors += 1

        history.append(enriched)
        normal_count += 1

    return factual_rows, policy_rows, {
        "logged_method": logged_method,
        "task": task,
        "run": run_name,
        "normal_transitions": normal_count,
        "factual_predictions": len(factual_rows),
        "policy_decisions": len(policy_rows) // len(BASELINES),
        "errors": errors,
    }


def summarize_predictions(rows: list[dict], key: str) -> dict:
    if not rows:
        return {"n": 0}
    actual = np.asarray([row["actual_h1"] for row in rows], dtype=float)
    predicted = np.asarray([row[key] for row in rows], dtype=float)
    clipped = np.clip(predicted, -1.0, 1.0)
    actual_positive = actual > 0.0
    predicted_positive = predicted > 0.0
    true_positive = int(np.sum(actual_positive & predicted_positive))
    positive_predictions = int(np.sum(predicted_positive))
    positives = int(np.sum(actual_positive))
    return {
        "n": len(rows),
        "runs": len({(row["logged_method"], row["task"], row["run"]) for row in rows}),
        "mae": float(np.mean(np.abs(predicted - actual))),
        "clipped_mae": float(np.mean(np.abs(clipped - actual))),
        "sign_accuracy": float(np.mean(predicted_positive == actual_positive)),
        "new_incumbent_precision": (
            true_positive / positive_predictions if positive_predictions else None
        ),
        "new_incumbent_recall": true_positive / positives if positives else None,
        "pooled_spearman": safe_spearman(actual, predicted),
        "prediction_outside_target_range": float(np.mean(np.abs(predicted) > 1.0)),
    }


def summarize_policy(rows: list[dict]) -> dict:
    if not rows:
        return {"decisions": 0}
    factual = [row for row in rows if row["factual"]]
    stability = [
        row["stability_modal_share"] for row in rows
        if row["stability_modal_share"] is not None
    ]
    return {
        "decisions": len(rows),
        "mean_candidate_count": float(np.mean([
            row["candidate_count"] for row in rows
        ])),
        "historical_mcgs_agreement": float(np.mean([
            row["historical_mcgs_agreement"] for row in rows
        ])),
        "max_parent_rate": float(np.mean([
            row["selected_max_parent"] for row in rows
        ])),
        "mean_selected_parent_rank": float(np.mean([
            row["selected_parent_rank"] for row in rows
        ])),
        "mean_stability_modal_share": (
            float(np.mean(stability)) if stability else None
        ),
        "factual_matches": len(factual),
        "factual_new_incumbent_rate": (
            float(np.mean([row["factual_new_incumbent"] for row in factual]))
            if factual else None
        ),
        "factual_invalid_rate": (
            float(np.mean([row["factual_invalid"] for row in factual]))
            if factual else None
        ),
    }


def fmt(value, digits: int = 3) -> str:
    return "N/A" if value is None else f"{value:.{digits}f}"


def render_markdown(result: dict) -> str:
    prediction = result["factual_value_prediction"]
    policy = result["policy_replay_on_legacy_mcgs_runs"]
    names = {
        "progressive_mcgs": "MCGS",
        "bnvs_mean_greedy": "Mean-Greedy",
        "bnvs_ts": "BNVS-TS",
        "bnvs_ts_local": "BNVS-TS-local",
    }
    lines = [
        "# BNVS step-zero baseline comparison",
        "",
        "## Protocol",
        "",
        f"- {result['run_count']} historical runs were processed strictly prequentially; every prediction used only earlier transitions in the same run.",
        "- BNVS starts from the Bayesian prior at zero observations. No MCGS warm-up or hard observation threshold is used.",
        "- Mean-Greedy and BNVS-TS share the same H=1 target and exact 10 features; only the selection rule differs.",
        "- BNVS-TS-local shares the same 10 features, prior, and Thompson draw seeds, but valid labels use clipped parent-relative gain. Invalid outcomes remain -1.",
        "- Factual value metrics use all 42 runs. Policy replay is restricted to the 21 Legacy runs whose logged selector was Progressive MCGS.",
        "",
        "## Baselines",
        "",
        "| Method | Value model | Selection rule | Purpose |",
        "|---|---|---|---|",
        "| MCGS | None | Original logged Progressive MCGS | Original baseline |",
        "| Mean-Greedy | Bayesian linear, H=1 | Largest posterior mean | Test whether learned value alone is useful |",
        "| BNVS-TS | Bayesian linear, H=1 | Thompson Sampling | Test uncertainty-driven exploration |",
        "| BNVS-TS-local | Bayesian linear, local gain | Thompson Sampling | Isolate the effect of the target |",
        "",
        "## Factual H=1 value prediction on all runs",
        "",
        "TS does not change the posterior mean, so Mean-Greedy and BNVS-TS have the same value-model row here; their difference appears in policy replay.",
        "",
        "| Method | N | MAE | Clipped MAE | Sign accuracy | Precision | Recall | Spearman | Outside [-1,1] |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for method, key in (
        ("Mean-Greedy / BNVS-TS", "bnvs_h1_mean"),
        ("BNVS-TS-local", "bnvs_local_as_h1_mean"),
    ):
        item = prediction[key]
        lines.append(
            f"| {method} | {item['n']} | {fmt(item['mae'])} | "
            f"{fmt(item['clipped_mae'])} | {fmt(item['sign_accuracy'])} | "
            f"{fmt(item['new_incumbent_precision'])} | "
            f"{fmt(item['new_incumbent_recall'])} | "
            f"{fmt(item['pooled_spearman'])} | "
            f"{fmt(item['prediction_outside_target_range'])} |"
        )
    lines.extend([
        "",
        "## Factual prediction by available history",
        "",
        "| Prior normal observations | N | H=1 clipped MAE | H=1 sign accuracy | Local clipped MAE | Local sign accuracy |",
        "|---|---:|---:|---:|---:|---:|",
    ])
    for bucket in ("0", "1-2", "3-5", "6-9", "10+"):
        h1 = result["factual_by_history_bucket"][bucket]["bnvs_h1_mean"]
        local = result["factual_by_history_bucket"][bucket][
            "bnvs_local_as_h1_mean"
        ]
        lines.append(
            f"| {bucket} | {h1['n']} | {fmt(h1.get('clipped_mae'))} | "
            f"{fmt(h1.get('sign_accuracy'))} | {fmt(local.get('clipped_mae'))} | "
            f"{fmt(local.get('sign_accuracy'))} |"
        )
    lines.extend([
        "",
        "## Candidate-policy replay on historical MCGS states",
        "",
        "| Method | Decisions | Candidates | Agreement with MCGS | Select max parent | Mean parent rank | Stability modal share | Factual matches | New incumbent on matches | Invalid on matches |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ])
    for key in BASELINES:
        item = policy[key]
        lines.append(
            f"| {names[key]} | {item['decisions']} | "
            f"{fmt(item['mean_candidate_count'])} | "
            f"{fmt(item['historical_mcgs_agreement'])} | "
            f"{fmt(item['max_parent_rate'])} | "
            f"{fmt(item['mean_selected_parent_rank'])} | "
            f"{fmt(item['mean_stability_modal_share'])} | "
            f"{item['factual_matches']} | "
            f"{fmt(item['factual_new_incumbent_rate'])} | "
            f"{fmt(item['factual_invalid_rate'])} |"
        )
    lines.extend([
        "",
        "The matched-outcome columns are descriptive only: each replay policy exposes outcomes on a different selected subset, so their rates are not a causal policy ranking.",
        "",
        "## Agreement with MCGS by available history",
        "",
        "| History observations | MCGS | Mean-Greedy | BNVS-TS | BNVS-TS-local |",
        "|---|---:|---:|---:|---:|",
    ])
    for bucket in ("0", "1-2", "3-5", "6-9", "10+"):
        bucket_result = result["policy_by_history_bucket"][bucket]
        lines.append(
            f"| {bucket} | " + " | ".join(
                fmt(bucket_result[key].get("historical_mcgs_agreement"))
                for key in BASELINES
            ) + " |"
        )
    lines.extend([
        "",
        "## Evidence boundary",
        "",
        "- Factual prediction evaluates the surrogate only on the action actually taken by the historical policy.",
        "- Candidate replay reveals policy shift, prior behavior, and selection stability, but unselected actions have no outcomes.",
        "- Only MCGS has outcomes for every row in the Legacy histories. Final-score superiority of the three BNVS variants requires randomized online runs.",
        "- Root drafts, debug, aggregation, and other structurally forced paths remain outside normal BNVS ranking; this is not a cold-start fallback.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs-root", type=Path, required=True)
    parser.add_argument("--stability-seeds", type=int, default=32)
    parser.add_argument(
        "--output-json",
        type=Path,
        default=REPO_ROOT / "docs" / "BNVS_BASELINE_OFFLINE_COMPARISON.json",
    )
    parser.add_argument(
        "--output-md",
        type=Path,
        default=REPO_ROOT / "docs" / "BNVS_BASELINE_OFFLINE_COMPARISON.md",
    )
    args = parser.parse_args()
    runs_root = args.runs_root.resolve()
    paths = sorted(runs_root.glob("*/*/*/logs/phase1/transitions.jsonl"))
    if not paths:
        raise SystemExit(f"no transition logs found under {runs_root}")

    factual_rows: list[dict] = []
    policy_rows: list[dict] = []
    summaries = []
    for path in paths:
        factual, policy, summary = evaluate_run(
            path,
            runs_root=runs_root,
            stability_seeds=max(int(args.stability_seeds), 1),
        )
        factual_rows.extend(factual)
        policy_rows.extend(policy)
        summaries.append(summary)

    result = json_safe({
        "runs_root": str(runs_root),
        "run_count": len(paths),
        "legacy_mcgs_run_count": sum(
            summary["logged_method"] == "Legacy" for summary in summaries
        ),
        "stability_seeds": max(int(args.stability_seeds), 1),
        "errors": sum(summary["errors"] for summary in summaries),
        "factual_value_prediction": {
            key: summarize_predictions(factual_rows, key)
            for key in ("bnvs_h1_mean", "bnvs_local_as_h1_mean")
        },
        "factual_by_history_bucket": {
            bucket: {
                key: summarize_predictions(
                    [row for row in factual_rows if row["history_bucket"] == bucket],
                    key,
                )
                for key in ("bnvs_h1_mean", "bnvs_local_as_h1_mean")
            }
            for bucket in ("0", "1-2", "3-5", "6-9", "10+")
        },
        "policy_replay_on_legacy_mcgs_runs": {
            baseline: summarize_policy([
                row for row in policy_rows if row["baseline"] == baseline
            ])
            for baseline in BASELINES
        },
        "policy_by_history_bucket": {
            bucket: {
                baseline: summarize_policy([
                    row for row in policy_rows
                    if row["baseline"] == baseline
                    and row["history_bucket"] == bucket
                ])
                for baseline in BASELINES
            }
            for bucket in ("0", "1-2", "3-5", "6-9", "10+")
        },
        "run_summaries": summaries,
    })
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_md.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(
        json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    args.output_md.write_text(render_markdown(result), encoding="utf-8")
    print(json.dumps({
        "run_count": result["run_count"],
        "errors": result["errors"],
        "factual_value_prediction": result["factual_value_prediction"],
        "policy_replay_on_legacy_mcgs_runs": result[
            "policy_replay_on_legacy_mcgs_runs"
        ],
    }, ensure_ascii=False, indent=2))
    print(f"wrote {args.output_json}")
    print(f"wrote {args.output_md}")


if __name__ == "__main__":
    main()
